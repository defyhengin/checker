def running(t):
    return float(ss(0.75, 0.9, t) * (1 - ss(13.55, 13.65, t)))


def tex(mid, Px, Py, Pz, alb, nx, ny, nz, t):
    w = mid == 1
    gx = (Px * 6) % 1; gy = (Py * 6) % 1
    alb[w] *= np.where((gx < 0.04) | (gy < 0.04), 0.45, 1.0)[w][:, None]
    m = mid == 4
    ang = np.arctan2(Pz, Px + 0.075) - t * 1.1 * (1 if t < 13.6 else 0)
    rr = np.sqrt((Px + 0.075) ** 2 + Pz ** 2)
    stripe = ((ang % (2 * np.pi / 3)) < 0.18) | (np.abs(rr - 0.1) < 0.006)
    alb[m] *= np.where(stripe, 0.55, 1.0)[m][:, None]
    return alb, nx, ny, nz


def post(col, D, cam, best, t):
    tz = (WZ - cam[2]) / D[2]
    hx = cam[0] + D[0] * tz; hy = cam[1] + D[1] * tz
    win = (tz > 0) & (best > tz) & (hx > -0.24) & (hx < 0.09) & (hy > 0.96) & (hy < 1.16)
    col[win] = col[win] * 0.55 + 0.012
    return col


def build(t):
    k = float(ss(0.5, 13.0, t))
    cam = lerp((-0.4, 1.32, -1.3), (-0.06, 1.1, -0.55), k)
    tgt = lerp((0.0, 1.05, 0.0), (-0.07, 1.03, 0.05), k)
    on = running(t)
    hum = 1 - 0.04 * np.sin(t * 41) * np.sin(t * 3.1) ** 2
    if t < 13.6:
        disp = 1.0
    else:
        disp = 1.0 if int((t - 13.6) * 2.5) % 2 == 0 else 0.15
    return dict(cam=cam, tgt=tgt, tanx=0.42, prims=PRIMS, alb=ALB, spec=SPEC, tex=tex, post=post, amb=0.002, exp=1.35,
                emit={6: np.array([0.25, 1.2, 0.45], f32) * disp},
                lights=[dict(p=(0.05, 1.17, 0.12), col=(1.0, 0.82, 0.5), I=0.25 * on * hum, att=(0.02, 4.0)),
                        dict(p=(-2.0, 3.0, -2.0), col=(0.5, 0.6, 0.85), I=0.5, att=(1.0, 0.05)),
                        dict(p=(0.21, 1.14, -0.3), col=(0.3, 1.0, 0.45), I=0.008 * disp, att=(0.01, 3.0), shadow=False)])


if __name__ == '__main__':
    main(build, 'mic')
