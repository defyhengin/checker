import numpy as np
from eng import box, cyl, disc, sph, ss, lerp, main, f32

ALB = np.array([(0.42, 0.30, 0.18), (0.48, 0.34, 0.20), (0.86, 0.86, 0.84), (0.55, 0.56, 0.58),
                (0.60, 0.45, 0.25), (0.30, 0.20, 0.12), (0.16, 0.15, 0.14)], f32)
SPEC = np.array([0.04, 0.06, 0.3, 0.9, 0.0, 0.05, 0.0], f32)

PRIMS = [
    box((-0.65, -0.05, 0.5), (0.65, 1.25, 0.55), 0),
    box((-0.65, -0.05, -0.3), (-0.6, 1.25, 0.55), 0),
    box((0.6, -0.05, -0.3), (0.65, 1.25, 0.55), 0),
    box((-0.65, 1.2, -0.3), (0.65, 1.25, 0.55), 0),
    box((-0.65, -0.05, -0.3), (0.65, 0.0, 0.55), 0),
    box((-0.6, 0.39, -0.28), (0.6, 0.41, 0.5), 1),
    box((-0.6, 0.79, -0.28), (0.6, 0.81, 0.5), 1),
    cyl(0.3, 0.15, 0.035, 0.41, 0.5, 2, 2), disc(0.3, 0.5, 0.15, 0.035, 2),
    cyl(0.3, 0.15, 0.03, 0.5, 0.53, 3, 3), disc(0.3, 0.53, 0.15, 0.03, 3),
    sph((-0.2, 0.006, 0.1), 0.006, 4), sph((-0.15, 0.005, 0.22), 0.005, 4), sph((0.05, 0.415, 0.3), 0.005, 4),
    box((-5, -3, 0.55), (5, 5, 0.6), 6),
]
KEYS = [(0.0, (0.0, 0.6, 0.5)), (1.2, (-0.35, 1.0, 0.4)), (3.0, (0.35, 1.0, 0.4)), (5.0, (-0.35, 0.2, 0.4)),
        (6.8, (0.3, 0.2, 0.4)), (8.4, (-0.3, 0.6, 0.4)), (10.0, (0.3, 0.47, 0.15))]


def aim(t):
    if t >= KEYS[-1][0]:
        p = KEYS[-1][1]
    else:
        for (t0, a), (t1, b) in zip(KEYS, KEYS[1:]):
            if t0 <= t < t1:
                p = lerp(a, b, float(ss(0, 1, (t - t0) / (t1 - t0))))
                break
    return (p[0] + 0.01 * np.sin(t * 6.1), p[1] + 0.008 * np.sin(t * 4.7), p[2])


def power(t):
    v = float(ss(0.55, 0.65, t))
    if t > 12.6:
        k = min((t - 12.6) / 1.4, 1)
        if np.sin(t * 29) * np.sin(t * 11 + 2) > 0.6 - 0.6 * k:
            v *= 0.25
        v *= 1 - 0.4 * float(ss(13.2, 14, t))
    if t > 14.0:
        v *= np.exp(-(t - 14) * 30)
    return v


def tex(mid, Px, Py, Pz, alb, nx, ny, nz, t):
    m = (mid == 0) | (mid == 1)
    g = 0.84 + 0.13 * np.sin((Px * 0.7 + Pz) * 38 + 5 * np.sin(Py * 4 + Px * 2)) + 0.05 * np.sin(Px * 160)
    alb[m] *= g[m][:, None]
    return alb, nx, ny, nz


def build(t):
    k = float(ss(9.8, 13.5, t))
    cam = lerp((0.0, 0.62, -1.5), (0.2, 0.58, -0.55), k)
    tgt = lerp((0.0, 0.6, 0.1), (0.3, 0.47, 0.15), k)
    lp = (cam[0] + 0.08, cam[1] - 0.06, cam[2] + 0.02)
    a = aim(t)
    return dict(cam=cam, tgt=tgt, tanx=0.42, prims=PRIMS, alb=ALB, spec=SPEC, tex=tex, amb=0.003, exp=1.4,
                lights=[dict(p=lp, col=(0.95, 0.97, 1.0), I=1.5 * power(t), att=(0.15, 1.0),
                             dir=(a[0] - lp[0], a[1] - lp[1], a[2] - lp[2]), cos=(0.9, 0.975))])


if __name__ == '__main__':
    main(build, 'cup')
